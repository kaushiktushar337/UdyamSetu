ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PROFILE_CSV = ROOT / "seed_data" / "business_reference_profiles_database_ready.csv"
DEMO_METRICS_SOURCE = "UdyamSetu development seed"
PROFILE_SOURCE = "KVIC/PMEGP/MSME official project profile"
MAX_DB_VARCHAR = 200

def fit_text(value: Any, max_length: int = MAX_DB_VARCHAR) -> str | None:
    """Safely fit optional text into the database VARCHAR limit.

    The DB team may have VARCHAR(200) even if a newer reference schema uses TEXT.
    This keeps the seed portable across both versions without changing the schema.
    """
    if value is None:
        return None
    text = str(value).strip()
    return text[:max_length] if text else None

