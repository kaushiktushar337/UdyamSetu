"""Seed UdyamSetu reference data into PostgreSQL.

Populates the tables that can safely have reference/demo data before real users exist:
  - business_reference_profiles (40 researched profiles)
  - location_reference (curated Indian location centroids)
  - location_business_metrics (development baseline metrics for Business Insights)

The location-business metrics generated by this script are explicitly labelled as
DEVELOPMENT SEED data. They are not presented as observed market statistics. Replace
or overwrite them with validated market data before using them as real-world claims.

Tables intentionally NOT seeded:
  - user_locations: populated by live user location capture
  - business_analyses and child analysis tables: populated by real analyses
  - conversations/messages: populated by chatbot use

Usage (PowerShell):
  python database/seed_reference_data.py --dry-run
  python database/seed_reference_data.py

Requires DATABASE_URL in .env or environment.
"""
